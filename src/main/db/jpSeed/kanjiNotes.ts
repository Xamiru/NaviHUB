// The kanji course with each kanji card's hook filled in from `notes`. A card
// that already carries its own note keeps it.
export function withKanjiNotes(course: SeedCourseDef, notes: Record<string, string>): SeedCourseDef {
  return {
    ...course,
    lessons: course.lessons.map((lesson) =>
      lesson.kind !== 'kanji'
        ? lesson
        : { ...lesson, cards: lesson.cards.map((card) => (card.notes || !notes[card.front] ? card : { ...card, notes: notes[card.front] })) }
    )
  }
}
